'use strict';
// Regenerates tests/i18n-literals-baseline.json. Run it deliberately after a
// localized work unit: the checked-in baseline may only decrease.
//
// A file that keeps a counted literal must record why that value is not copy a
// translator can act on: a product name, a format name, an example value that
// only works verbatim, or a technical label. `tests/i18n-literals-exemptions.test.cjs`
// fails when a remaining literal has no reason and when a recorded reason no
// longer matches the source, so the list cannot rot silently.
const fs = require('node:fs');
const path = require('node:path');
const { scanRepository, ROOT } = require('./i18n-literals-scanner.cjs');

// Product names of the external tools the settings screens connect to. They are
// vendor identities, not interface copy, and they read the same in both locales.
const PRODUCT_NAMES = 'Vendor product name rendered as-is; translating it would rename the product.';

const EXEMPTIONS = {
  'index.html': {
    AnyDesk: PRODUCT_NAMES,
    'Tactical RMM': PRODUCT_NAMES
  },
  'assets/js/agent-integrations.js': {
    OpenCode: PRODUCT_NAMES,
    Hermes: PRODUCT_NAMES,
    'Pydantic AI': PRODUCT_NAMES,
    '· Pydantic AI': 'Separator plus the vendor product name of the engine that answers.',
    'SHA-256': 'Digest algorithm name shown beside the credential fingerprint.',
    v: 'Prefix of a version number; the number itself comes from the server.',
    'placeholder=http://127.0.0.1:4096': 'Example OpenCode server endpoint; a URL only works verbatim.',
    'placeholder=http://127.0.0.1:8000/mcp': 'Example MCP server endpoint; a URL only works verbatim.',
    'placeholder=OPENCODE_SERVER_PASSWORD': 'Name of the environment variable the field expects.',
    'placeholder=ITSM_MCP_TOKEN': 'Name of the environment variable the field expects.',
    'placeholder=America/Mexico_City': 'Example IANA time zone identifier accepted by the field.'
  },
  'assets/js/report-views.js': {
    v: 'Prefix of a template version number; the number itself comes from the server.',
    'placeholder=https://activos.organizacion.example/': 'Example base URL; a host name is not translated.',
    'placeholder=#0d766e': 'Example hexadecimal colour accepted by the field.',
    'placeholder=#147c73': 'Example hexadecimal colour accepted by the field.'
  },
  'assets/js/search-views.js': {
    Meilisearch: 'Name of the search engine the server reports; it is not a translatable label.',
    SQL: 'Name of the built-in storage engine the server reports.'
  },
  'assets/js/transfer-export-views.js': {
    CSV: 'Output format name; the same token names the file the server produces.'
  },
  'assets/js/conversation.js': {
    'SHA-256:': 'Digest algorithm label of the review fingerprint shown to the user.'
  },
  'assets/js/label-views.js': {
    '·   ·   ×   mm': 'Page-size separators and the millimetre unit symbol; the measurements come from the server format.'
  }
};

if (require.main === module) {
  const report = scanRepository();
  const target = path.join(ROOT, 'tests/i18n-literals-baseline.json');
  const payload = {
    note: 'Human-visible hard-coded copy still awaiting a catalog key. Generated by tests/i18n-literals-baseline.cjs; counts may only go down.',
    total: report.total,
    files: report.files,
    exemptions: EXEMPTIONS
  };
  fs.writeFileSync(target, JSON.stringify(payload, null, 2) + '\n');
  console.log('baseline written: ' + report.total + ' literals in ' + Object.keys(report.files).length + ' files');
}

module.exports = { EXEMPTIONS };
