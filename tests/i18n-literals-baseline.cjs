'use strict';
// Regenerates tests/i18n-literals-baseline.json. Run it deliberately after a
// localized work unit: the checked-in baseline may only decrease.
const fs = require('node:fs');
const path = require('node:path');
const { scanRepository, ROOT } = require('./i18n-literals-scanner.cjs');

if (require.main === module) {
  const report = scanRepository();
  const target = path.join(ROOT, 'tests/i18n-literals-baseline.json');
  const payload = {
    note: 'Human-visible hard-coded copy still awaiting a catalog key. Generated by tests/i18n-literals-baseline.cjs; counts may only go down.',
    total: report.total,
    files: report.files
  };
  fs.writeFileSync(target, JSON.stringify(payload, null, 2) + '\n');
  console.log('baseline written: ' + report.total + ' literals in ' + Object.keys(report.files).length + ' files');
}
