test('production purge demands the archived asset, the typed id and a reason', async () => {
  const { c, app } = setup();
  const calls = withCatalog(c, app);
  await app.loadInventoryCatalog();
  const active = app.inventoryMapAsset(dto({ archived: false }));

  app.openInventoryLifecycle(active, 'purge');
  assert.match(app.inventoryLifecycle.error, /archiv/i);
  assert.equal(await app.confirmInventoryLifecycle(), false);
  assert.equal(calls.filter((call) => call.url.endsWith('/purge')).length, 0);

  const archived = app.inventoryMapAsset(dto({ archived: true, archivedAt: '2026-02-01T10:00:00Z' }));
  app.openInventoryLifecycle(archived, 'purge');
  assert.equal(app.inventoryLifecycle.open, true);
  app.inventoryLifecycle.typed = 'no-es-el-id';
  app.inventoryLifecycle.reason = 'Duplicado creado por error';
  assert.equal(await app.confirmInventoryLifecycle(), false);
  assert.match(app.inventoryLifecycle.error, /ID permanente/);
  assert.equal(calls.filter((call) => call.url.endsWith('/purge')).length, 0);

  app.inventoryLifecycle.typed = ASSET_ID;
  assert.ok(await app.confirmInventoryLifecycle());
  const purge = calls.find((call) => call.url.endsWith('/purge'));
  assert.deepEqual(purge.body, { confirm: true, typedId: ASSET_ID, reason: 'Duplicado creado por error' });
});

