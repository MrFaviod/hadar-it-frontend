test('clone, archive, restore and retire use their real endpoints and reload', async () => {
  const { c, app } = setup();
  const calls = stubFetch(c, (call) => {
    if (call.url === '/api/v1/inventory/config') return json(catalog());
    if (call.url.indexOf('/clone') !== -1) return json(dto({ id: OTHER_ID, quickCode: 'NB-CEN-002' }), 201);
    return json(dto());
  });
  await app.loadInventoryCatalog();
  const asset = app.inventoryMapAsset(dto());

  assert.ok(await app.cloneInventoryAsset(asset));
  assert.equal(calls[1].url, '/api/v1/assets/' + ASSET_ID + '/clone');
  assert.equal(calls[1].init.method, 'POST');

  assert.ok(await app.archiveInventoryAsset(asset, 'Equipo retirado del aula'));
  const archive = calls.find((call) => call.url.endsWith('/archive'));
  assert.equal(archive.init.method, 'POST');
  assert.deepEqual(archive.body, { reason: 'Equipo retirado del aula' });

  const archived = app.inventoryMapAsset(dto({ archived: true, archivedAt: '2026-02-01T10:00:00Z' }));
  assert.ok(await app.restoreInventoryAsset(archived));
  assert.ok(calls.some((call) => call.url.endsWith('/restore') && call.init.method === 'POST'));

  assert.equal(await app.retireInventoryAsset(asset, 'Avería irreparable'), true);
  const retire = calls.find((call) => call.url.endsWith('/retire'));
  assert.deepEqual(retire.body, { reason: 'Avería irreparable' });
  assert.match(calls[calls.length - 1].url, /^\/api\/v1\/assets\/search\?/);
});

