test('configuration mutations are non-destructive and reload the catalog', async () => {
  const { c, app } = setup();
  const calls = stubFetch(c, (call) => {
    if (call.init.method === 'PUT') return json({});
    return json(catalog({ statuses: catalog().statuses.concat([{ id: 'obsolete2', label: 'Obsoleto', tone: 'hold', final: false, active: false }]) }));
  });
  await app.loadInventoryCatalog();

  assert.ok(await app.saveInventoryField({ mode: 'create', key: 'gpu', label: 'GPU', type: 'text', unit: '', hint: '', options: '', required: false, maxLength: 500 }));
  const fieldPut = calls.find((call) => call.init.method === 'PUT');
  assert.equal(fieldPut.url, '/api/v1/inventory/config/fields/gpu');
  assert.equal(fieldPut.body.type, 'text');
  assert.equal(fieldPut.body.active, true);

  assert.ok(await app.saveInventoryStatus({ mode: 'edit', id: 'obsolete', label: 'Obsoleto', tone: 'hold', final: false, active: false }));
  const statusPut = calls.filter((call) => call.init.method === 'PUT').pop();
  assert.equal(statusPut.url, '/api/v1/inventory/config/statuses/obsolete');
  assert.equal(statusPut.body.active, false, 'deactivation replaces deletion');

  assert.ok(await app.saveInventoryRules({ separator: '_', quickPad: 4, siteCodeLength: 2, includeSite: false, order: 'type-site' }));
  const rulesPut = calls.filter((call) => call.init.method === 'PUT').pop();
  assert.equal(rulesPut.url, '/api/v1/inventory/config/rules/identification');
  assert.equal(rulesPut.body.order, 'type-site');
  assert.equal(rulesPut.body.separator, '_');
  assert.equal(app.inventoryCatalog.loaded, true, 'the catalog is reloaded after a mutation');
});

