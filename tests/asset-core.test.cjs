test('create posts cost and typed technical values that the API accepts', async () => {
  const { c, app } = setup();
  const saved = dto({ cost: '1250.50', technical: { cpu: 'Ryzen 7', ram: 32, poe: true, os: 'Linux', installedAt: '2026-01-02' } });
  const calls = stubFetch(c, (call) => {
    if (call.url === '/api/v1/inventory/config') return json(catalog());
    if (call.init.method === 'POST') return json(saved, 201);
    return json({ items: [saved], total: 1, limit: 25, offset: 0 });
  });
  await app.loadInventoryCatalog();
  assert.ok(app.openAssetCreate());

  const draft = app.assetEditor.draft;
  draft.name = 'Notebook nueva';
  draft.cost = '1250.50';
  draft.technical = { cpu: 'Ryzen 7', ram: '32', poe: true, os: 'Linux', installedAt: '2026-01-02' };

  assert.ok(await app.saveAsset());

  const post = calls.find((call) => call.init.method === 'POST');
  assert.equal(post.url, '/api/v1/assets');
  assert.equal(post.body.name, 'Notebook nueva');
  assert.equal(post.body.category, 'Notebooks', 'the server receives the stable catalog label');
  assert.equal(post.body.cost, '1250.50', 'cost stays a bounded decimal string');
  assert.deepEqual(post.body.technical, { cpu: 'Ryzen 7', ram: 32, poe: true, os: 'Linux', installedAt: '2026-01-02' });
  assert.equal('id' in post.body, false);
  assert.equal('code' in post.body, false);
  assert.equal('quickCode' in post.body, false, 'a blank quick code is generated by the server');
  assert.equal('statusId' in post.body, false);
  assert.match(calls[calls.length - 1].url, /^\/api\/v1\/assets\/search\?/, 'the list is reloaded from the server');
});

