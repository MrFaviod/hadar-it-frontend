const { setup, json, stubFetch, dto, catalog, ASSET_ID, OTHER_ID } = require('./inventory-harness.cjs');

function withCatalog(c, app, payload) {
  return stubFetch(c, (call) => {
    if (call.url.indexOf('/api/v1/inventory/config') === 0) return json(payload || catalog());
    return json({ items: [dto()], total: 1, limit: 25, offset: 0 });
  });
}

