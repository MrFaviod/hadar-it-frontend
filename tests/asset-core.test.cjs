test('photo upload sends raw bytes and rejects SVG or oversized files locally', async () => {
  const { c, app } = setup();
  const calls = withCatalog(c, app);
  await app.loadInventoryCatalog();
  const asset = app.inventoryMapAsset(dto());
  const bytes = new Uint8Array([0x89, 0x50, 0x4e, 0x47]);

  assert.equal(await app.uploadInventoryImage(asset, 'photo', { type: 'image/svg+xml', size: 12 }), false);
  assert.equal(await app.uploadInventoryImage(asset, 'photo', { type: 'image/png', size: 2 * 1024 * 1024 }), false);
  assert.equal(calls.filter((call) => call.url.indexOf('/images/') !== -1).length, 0);

  c.AssetAccess.request = (vm, path, options) => {
    calls.push({ url: path, init: options || {}, rawBody: options && options.body });
    return Promise.resolve({ role: 'photo', contentType: 'image/png', size: 4, url: '/api/v1/assets/' + ASSET_ID + '/images/photo', updatedAt: '2026-02-02T10:00:00Z' });
  };

  assert.equal(await app.uploadInventoryImage(asset, 'photo', { type: 'image/png', size: 4, arrayBuffer: async () => bytes.buffer }), true);
  const put = calls.find((call) => call.url.indexOf('/images/') !== -1);
  assert.equal(put.init.method, 'PUT');
  assert.match(put.url, new RegExp('/assets/' + ASSET_ID + '/images/photo$'));
  assert.equal(put.init.body instanceof ArrayBuffer, true, 'the image body is binary, not JSON');
  assert.equal(put.init.headers, undefined, 'the browser sets the binary content type');
});

